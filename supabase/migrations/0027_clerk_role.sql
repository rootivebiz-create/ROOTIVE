-- =============================================================================
-- 0027 事務員ロール（1/2）：user_role に clerk を足すだけ
--
--   Postgres では、enum に足した値は「足したのと同じトランザクションの中」では使えない。
--   Supabase の API はマイグレーションを 1 ファイル 1 トランザクションで流すため、
--   値を使う側（is_admin などの判定・ポリシー）は 0028 に分けている。
-- =============================================================================
alter type public.user_role add value if not exists 'clerk' after 'admin';
