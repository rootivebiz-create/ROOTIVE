import { EXPORT_TABLES, NOT_EXPORTED_TABLES } from "./tables";

/** ISO の日時 → 日本時間の「2026-10-31 18:05」 */
function jstText(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  const j = new Date(d.getTime() + 9 * 3600_000).toISOString();
  return `${j.slice(0, 10)} ${j.slice(11, 16)}`;
}

/**
 * 書き出しの ZIP に入れる「はじめにお読みください」（README.txt）。
 * 会社の人が、しめ日ラボが無くても中身を読めるように、ファイルごとの説明を書く。
 */
export function readmeText(opts: { tenantName: string; exportedAt: string; schemaVersion: string; counts: Record<string, number>; versions: number }): string {
  const lines: string[] = [];
  const add = (...l: string[]) => lines.push(...l);
  add(
    "しめ日ラボ　全データの書き出し",
    "==============================",
    "",
    `会社：${opts.tenantName}`,
    `書き出した日時：${jstText(opts.exportedAt)}（日本時間）／${opts.exportedAt}（協定世界時）`,
    `データの形の版：${opts.schemaVersion}`,
    "",
    "この ZIP には、しめ日ラボに入っているこの会社のデータが、すべて入っています。",
    "しめ日ラボをやめたあとも、表計算ソフト（Excel など）や、ほかのシステムで読めます。",
    "",
    "■ 入っているもの",
    "",
    "manifest.json",
    "  書き出しの目録です。データの形の版・表ごとの行数・各ファイルのハッシュ（sha256）が入っています。",
    "  読み戻すときに、ファイルが途中で壊れていないか・書き換えられていないかを、このハッシュで確かめます。",
    "",
    "statement_versions/（フォルダー）",
    `  支払明細のすべての版（${opts.versions}件）を、1 版 1 ファイルの JSON で入れています。`,
    "  ファイル名は「明細の id-v版.json」で、月ごとのフォルダーに分けています。",
    "  hash は、その版の中身（snapshot）から作ったハッシュで、ドライバーが「確認しました」を押したときの記録（statement_confirmations.csv の hash）と照らし合わせられます。",
    "",
    "csv/（フォルダー）表ごとの CSV",
  );
  for (const t of EXPORT_TABLES) {
    add(`  csv/${t.name}.csv　${t.label}（${opts.counts[t.name] ?? 0}行）`, `    ${t.about}`);
  }
  add(
    "",
    "■ CSV の読み方",
    "",
    "・文字コードは UTF-8（BOM 付き）、行の区切りは CRLF です。Excel でそのまま開けます。",
    "・1 行目は見出しで、データベースの列の名前（英字）をそのまま入れています。",
    "・金額は円の整数です（税抜・税込は列の名前と明細の中身で分かれます）。単価・数量は小数を含むことがあります。",
    "・日付は YYYY-MM-DD、日時は ISO 8601（末尾の +00:00 は協定世界時。日本時間は 9 時間進めてください）。",
    "・month の列は、その月の 1 日（例：2026-10-01 は 2026年10月分）です。",
    "・引用符の無い空欄は「値なし」、\"\"（引用符だけ）は「空の文字」です。",
    "・文字の頭が = + - @ ' のものは、表計算ソフトで式として動かないよう、頭に ' を 1 つ付けています（読み戻すときに外します）。",
    "・[ ] や { } で始まる列（別名・設定・明細の中身など）は JSON です。",
    "・id の列どうしで表をつなげられます（例：work_entries.csv の driver_id は drivers.csv の id）。",
    "",
    "■ 入っていないもの",
    "",
  );
  for (const t of NOT_EXPORTED_TABLES) add(`・${t.name}（${t.reason}）`);
  add(
    "・利用者のパスワード（users の password_hash）。読み戻したあとは、招待のリンクからパスワードを決め直します。",
    "・招待のリンクの値（invites の token_hash）。",
    "・取り込んだ Excel・CSV の元のファイル（取り込んだ中身は work_entries.csv と import_batches.csv に入っています）。",
    "・人が読むための PDF（支払明細・取引条件の明示書）。この ZIP は機械で読み戻すための形です。",
    "",
    "■ 読むための PDF（支払明細・取引条件の明示書）",
    "",
    "支払明細と取引条件の明示書を、人が読める PDF で残したいときは、「全データの書き出し」の画面の「読むための PDF を書き出す」から、年ごとの ZIP を別に保存してください。",
    "その年のすべての版（作り直した前の版も）が、月ごとの PDF と目録（目録.csv）で入ります。しめ日ラボをやめる前に、要る年の分をすべて保存してください。",
    "",
    "■ 別の場所へ移すとき（読み戻し）",
    "",
    "しめ日ラボの「全データの書き出し」の画面から、この ZIP をそのまま読み込めます。",
    "移した先で「最初の設定」をして会社を 1 つ作り、その会社のオーナーとしてログインしてから読み込みます（ほかの会社が入っている場所では読み込めません）。",
    "同じ会社がすでにある場所には読み込めません（二重になるのを防ぐため）。",
    "読み込んだあとは、明細のすべての版のハッシュと、表ごとの行数が同じかを確かめます。",
    "",
    "■ 保存について",
    "",
    "この ZIP には、ドライバーの口座・連絡先などの大切な情報が入っています。社外に出すときや保管するときは、扱いに気をつけてください。",
    "帳簿や書類をどのくらいの期間、どう保存するかは、会社で決めた決まりに沿ってください。判断に迷うときは、税理士にご相談ください。",
    "しめ日ラボは、保存期間を過ぎたデータを自動で消すことはしません。",
    "",
  );
  return lines.join("\r\n");
}
