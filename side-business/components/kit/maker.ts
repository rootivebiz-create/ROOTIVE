/**
 * 「作っている人」の書き方。サイト（トップ・運営者について）と営業資料（提案書・FAX・チラシ）で同じ文を使う。
 * 運送会社を経営していると書くのは SITE.makerIsOperator が true のときだけ（会社の承認で書いてよいと決めたとき）。
 * false のときは、会社のことに触れない中立の書き方にする。
 */
import { SITE } from "@/site.config";

export type MakerCopy = {
  /** トップの 3 つの約束の見出し */
  pointTitle: string;
  /** トップの 3 つの約束の説明 */
  pointBody: string;
  /** 「作っている人」の段落（トップ・提案書の表紙） */
  paragraph: string;
  /** FAX の 1 文 */
  fax: string;
  /** チラシの見出しの下の 1〜3 文 */
  flyer: string;
  /** 運営者についての、太字の導入 */
  aboutLead: string;
  /** 運営者についての、導入の次の段落 */
  aboutBody: string;
  /** 運営者についての、ページの説明（meta description） */
  aboutDescription: string;
};

export function makerCopy(isOperator: boolean = SITE.makerIsOperator): MakerCopy {
  if (isOperator) {
    return {
      pointTitle: "作るのは軽貨物会社の代表",
      pointBody: "自分の会社でも、支払明細と利益の管理を仕組みにして毎月使っています",
      paragraph:
        "作るのは、軽貨物の運送会社を経営している本人です。自分の会社でも、支払明細と利益の管理を仕組みにして毎月使っています。AIを使って作るので、早く、手ごろに作れます。",
      fax: "作るのは、軽貨物の運送会社を経営している本人です。",
      flyer:
        "作っているのは、同じ軽貨物の運送会社を経営している本人です。自分の会社でも同じような仕組みを毎月使っています。その経験をもとに、御社のやり方に合わせて作ります。",
      aboutLead:
        "運営しているのは、軽貨物の運送会社を経営している本人です。自分の会社で、支払明細・利益の管理・点呼の記録を仕組みにして、毎日使っています。",
      aboutBody:
        "この仕組みづくりは、その運送会社の事業ではなく、本人の個人事業として行っています。現場で使っている立場から、同じように月末の締めに追われている運送会社の仕組みを作ります。",
      aboutDescription: `${SITE.name}を運営しているのは、軽貨物の運送会社を経営している本人です。支払明細・利益の管理・点呼の記録を自分の会社で仕組みにして、毎日使っています。進め方・やらないこと・データの扱いをまとめました。`,
    };
  }
  return {
    pointTitle: "運送業の支払に詳しい作り手",
    pointBody: "単価・控除・元請ごとの締めを分かったうえで、AIを使って作ります",
    paragraph:
      "運送業の支払の仕組みに詳しい作り手が、AIを使って作ります。単価・控除・元請ごとの締めなど、御社のやり方を伺ってから、そのまま仕組みにします。AIを使うので、早く、手ごろに作れます。",
    fax: "運送業の支払の仕組みに詳しい作り手が、AIを使って作ります。",
    flyer:
      "運送業の支払の仕組みに詳しい作り手が、AIを使って作ります。御社の今のやり方を伺ってから、そのまま仕組みにします。",
    aboutLead:
      "運営しているのは、運送業の支払の仕組みに詳しい作り手です。AIを使って、御社のやり方に合わせた仕組みを作ります。",
    aboutBody:
      "この仕組みづくりは、個人事業として行っています。月末の締めに追われている運送会社のために、今のExcelのルールのまま使える仕組みを作ります。",
    aboutDescription: `${SITE.name}の運営者について。運送業の支払の仕組みに詳しい作り手が、AIを使って御社のやり方に合わせた仕組みを作ります。進め方・やらないこと・データの扱いをまとめました。`,
  };
}
